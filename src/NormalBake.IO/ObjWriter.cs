using System.Globalization;
using System.Numerics;
using System.Text;
using NormalBake.Core;

namespace NormalBake.IO;

/// <summary>
/// Writes Wavefront OBJ meshes. Vertex attributes are written one-to-one with the struct-of-arrays
/// layout (each vertex emits a matching <c>v</c>/<c>vt</c>/<c>vn</c>), so faces reference a single shared
/// index. Floats use round-trippable invariant formatting and lines are LF-terminated, so a written mesh
/// reads back identically. (OBJ has no tangent record; emitting tangents with the mesh is a later phase.)
/// </summary>
public static class ObjWriter
{
    private static readonly UTF8Encoding Utf8NoBom = new(encoderShouldEmitUTF8Identifier: false);

    /// <summary>Writes a high-poly mesh (positions + normals) to a file.</summary>
    public static void Write(string path, Mesh mesh)
    {
        ArgumentNullException.ThrowIfNull(path);
        ArgumentNullException.ThrowIfNull(mesh);
        using var stream = File.Create(path);
        Write(stream, mesh);
    }

    /// <summary>Writes a high-poly mesh (positions + normals) to a stream.</summary>
    public static void Write(Stream stream, Mesh mesh)
    {
        ArgumentNullException.ThrowIfNull(stream);
        ArgumentNullException.ThrowIfNull(mesh);
        using var writer = NewWriter(stream);
        WriteHeader(writer, mesh.VertexCount, mesh.TriangleCount);
        WritePositions(writer, mesh.Positions);
        WriteNormals(writer, mesh.Normals);
        WriteFaces(writer, mesh.Indices, hasUv: false);
    }

    /// <summary>Writes a low-poly mesh (positions + UVs + normals) to a file.</summary>
    public static void Write(string path, UvMesh mesh)
    {
        ArgumentNullException.ThrowIfNull(path);
        ArgumentNullException.ThrowIfNull(mesh);
        using var stream = File.Create(path);
        Write(stream, mesh);
    }

    /// <summary>Writes a low-poly mesh (positions + UVs + normals) to a stream.</summary>
    public static void Write(Stream stream, UvMesh mesh)
    {
        ArgumentNullException.ThrowIfNull(stream);
        ArgumentNullException.ThrowIfNull(mesh);
        using var writer = NewWriter(stream);
        WriteHeader(writer, mesh.VertexCount, mesh.TriangleCount);
        WritePositions(writer, mesh.Positions);
        WriteUvs(writer, mesh.Uvs);
        WriteNormals(writer, mesh.Normals);
        WriteFaces(writer, mesh.Indices, hasUv: true);
    }

    private static StreamWriter NewWriter(Stream stream) =>
        new(stream, Utf8NoBom, bufferSize: 4096, leaveOpen: true) { NewLine = "\n" };

    private static void WriteHeader(StreamWriter w, int vertices, int triangles)
    {
        w.WriteLine("# Generated by NormalBake");
        w.WriteLine(
            string.Create(CultureInfo.InvariantCulture, $"# {vertices} vertices, {triangles} triangles"));
    }

    private static void WritePositions(StreamWriter w, ReadOnlySpan<Vector3> positions)
    {
        foreach (Vector3 p in positions)
        {
            w.WriteLine(string.Create(
                CultureInfo.InvariantCulture, $"v {F(p.X)} {F(p.Y)} {F(p.Z)}"));
        }
    }

    private static void WriteUvs(StreamWriter w, ReadOnlySpan<Vector2> uvs)
    {
        foreach (Vector2 uv in uvs)
        {
            w.WriteLine(string.Create(CultureInfo.InvariantCulture, $"vt {F(uv.X)} {F(uv.Y)}"));
        }
    }

    private static void WriteNormals(StreamWriter w, ReadOnlySpan<Vector3> normals)
    {
        foreach (Vector3 n in normals)
        {
            w.WriteLine(string.Create(
                CultureInfo.InvariantCulture, $"vn {F(n.X)} {F(n.Y)} {F(n.Z)}"));
        }
    }

    private static void WriteFaces(StreamWriter w, ReadOnlySpan<int> indices, bool hasUv)
    {
        for (int t = 0; t + 2 < indices.Length; t += 3)
        {
            int a = indices[t] + 1;
            int b = indices[t + 1] + 1;
            int c = indices[t + 2] + 1;
            w.WriteLine(hasUv
                ? string.Create(CultureInfo.InvariantCulture, $"f {a}/{a}/{a} {b}/{b}/{b} {c}/{c}/{c}")
                : string.Create(CultureInfo.InvariantCulture, $"f {a}//{a} {b}//{b} {c}//{c}"));
        }
    }

    private static string F(float value) => value.ToString("R", CultureInfo.InvariantCulture);
}
